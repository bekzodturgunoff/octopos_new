/**
 * The old-URL 301s (vercel.json) in the formats the octopos.uz server stack
 * can use. octopos.uz is a static server behind the Cloudflare proxy, which
 * reads neither vercel.json nor _redirects, so apply ONE of these:
 *
 *   deploy/cloudflare-bulk-redirects.csv
 *     Cloudflare dashboard → Rules → Redirect Rules → Bulk Redirects →
 *     create a list, "Upload CSV", then a Bulk Redirect Rule using that list.
 *     Runs at Cloudflare's edge, before the request reaches the server.
 *
 *   deploy/nginx-redirects.conf
 *     For nginx: `include` it inside the octopos.uz `server { }` block.
 *
 *   node scripts/redirects.mjs        (re-run after changing vercel.json)
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const SITE = "https://octopos.uz";
const { redirects } = JSON.parse(fs.readFileSync(path.join(ROOT, "vercel.json"), "utf8"));
const out = path.join(ROOT, "deploy");
fs.mkdirSync(out, { recursive: true });

// Cloudflare Bulk Redirects CSV: source_url,target_url,status_code,
// preserve_query_string,include_subdomains,subpath_matching,preserve_path_suffix
const csv = redirects
  .map((r) => [`octopos.uz${r.source}`, SITE + r.destination, r.statusCode ?? 301, "TRUE", "FALSE", "FALSE", "FALSE"].join(","))
  .join("\n");
fs.writeFileSync(path.join(out, "cloudflare-bulk-redirects.csv"), csv + "\n");

// nginx: exact-match locations (the #fragment is kept in the Location header).
const esc = (s) => s.replace(/"/g, '\\"');
const nginx =
  "# Generated by scripts/redirects.mjs from vercel.json. Include inside the octopos.uz server { } block.\n" +
  redirects.map((r) => `location = "${esc(r.source)}" { return ${r.statusCode ?? 301} "${esc(r.destination)}"; }`).join("\n") +
  "\n";
fs.writeFileSync(path.join(out, "nginx-redirects.conf"), nginx);

console.log(`${redirects.length} redirects → deploy/cloudflare-bulk-redirects.csv, deploy/nginx-redirects.conf`);
